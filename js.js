// تعليق: جلب جميع عناصر الصور السبعة وعنصر العنوان من الـ HTML لربط حركتها بقيم التمرير
let a1 = document.getElementById('a1'); // نجوم الخلفية
let a2 = document.getElementById('a2'); // القمر المشع
let a3 = document.getElementById('a3'); // الجبال البعيدة
let a4 = document.getElementById('a4'); // الجبال المتوسطة
let a5 = document.getElementById('a5'); // الجبال القريبة
let a6 = document.getElementById('a6'); // مقدمة الأشجار أو القارب
let nouvil = document.querySelector('.nouvil'); // عنوان براندك الفخم (Qaisi Dev)

// تعليق: إطلاق دالة الاستماع للتمرير داخل نافذة المتصفح عند نزول المستخدم بالماوس
window.onscroll = function () {
    
    // تخزين قيمة التمرير العمودي الحالية بالبكسل داخل متغير باسم value
    let value = scrollY;
    
    // -------------------------------------------------------------
    // 📊 هندسة معادلات الحركة التتابعية وسرعات الطبقات (Parallax Logic)
    // -------------------------------------------------------------
    
    // تحريك النجوم أفقياً لخلق شعور بالدوران الفضائي السلس
    a1.style.left = value + 'px';
    
    // تحريك القمر لأسفل بسرعة مضاعفة 4 مرات لكي يختفي خلف الجبال سريعاً وبمنظر سينمائي
    a2.style.top = value * 4 + 'px';
    
    // تحريك الجبال البعيدة لأسفل بسرعة مضاعفة مرتين لخلق عمق بصري ثلاثي الأبعاد
    a3.style.top = value * 2 + 'px';
    
    // تحريك الجبال المتوسطة لأسفل بسرعة 1.5 مرة لتتناسب مع أبعاد الرؤية الوسطى
    a4.style.top = value * 1.5 + 'px';
    
    // تحريك الجبال القريبة لأسفل بنفس سرعة التمرير العادية 1:1 لتثبيتها نسبياً أمام العين
    a5.style.top = value + 'px';
    
    // تحريك المقدمة (الأشجار/القارب) لأسفل ولليمين بسرعة مضاعفة 3 مرات لصنع خروج حركي ممتع
    a6.style.top = value + 'px';
    a6.style.left = value * 3 + 'px';
    
    // تضخيم حجم خط اسم البراند تدريجياً بناءً على قيمة النزول لصنع تأثير زووم سينمائي
    nouvil.style.fontSize = value + 'px';
    
    // -------------------------------------------------------------
    // 🛡️ هندسة قيود الحجم والتثبيت لمنع تشوه الاسم وسط الشاشة
    // -------------------------------------------------------------
    
    // إذا وصل التمرير لـ 70 بكسل أو أكثر، ثبت حجم الخط عند 70 بكسل واجعله ثابتاً في مكانه
    if (scrollY >= 70) {
        nouvil.style.fontSize = 70 + 'px';
        nouvil.style.position = 'fixed';
        
        // إذا نزل المستخدم أكثر ووصل لـ 396 بكسل، قم بإخفاء الاسم تماماً لكي لا يتداخل مع نصوص المحتوى بالأسفل
        if (scrollY >= 396) {
            nouvil.style.display = 'none';
        }
    } else {
        // إذا عاد المستخدم لأعلى الشاشة، أظهر الاسم مجدداً بوضعه الطبيعي ككتلة
        nouvil.style.display = 'block';
    }
    
    // -------------------------------------------------------------
    // 🎨 هندسة التغير الزمني الهادئ والغامق لـ (وقت الفجر الأزرق العميق)
    // -------------------------------------------------------------
    
    // تعليق: عندما ينزل القمر ويصل التمرير لـ 131 بكسل، تتحول السماء ببطء لتدرج كحلي وأزرق ليلي غامق جداً يمثل الفجر الهادئ
    if (scrollY >= 131) {
        // تم استبدال الألوان الفاقعة بتدرج داكن فخم جداً يحافظ على غموض وجمال اللوحة
        document.querySelector('.main').style.background = 'linear-gradient(#0a1128, #101f42)';
    } else {
        // تعليق: عندما يكون القمر في الأعلى، نحافظ على اللون الأسود الملكي الصافي والفخم 100% لبراند Qaisi Dev
        document.querySelector('.main').style.background = 'linear-gradient(#05050a, #05050a)';
    }
}
